import { Badge, Button, FormField, FormSection, Input, useConfirm, useToast, type BreadcrumbEntry } from '@/components/core';
import AdminLayout from '@/layouts/admin-layout';
import SettingsLayout from '@/layouts/settings/layout';
import { __ } from '@/lib/i18n';
import { Head, router, useForm } from '@inertiajs/react';
import { Copy, KeyRound, RefreshCw, ShieldCheck, ShieldOff } from 'lucide-react';
import { useState, type FormEventHandler, type ReactNode } from 'react';

interface TwoFactorProps {
    state: 'disabled' | 'pending' | 'enabled';
    qrCodeSvg: string | null;
    secretKey: string | null;
    recoveryCodes: string[];
}

const breadcrumbs: BreadcrumbEntry[] = [
    { title: 'Settings', href: '/settings/profile' },
    { title: 'Two-factor', href: '/settings/two-factor' },
];

export default function TwoFactor({ state, qrCodeSvg, secretKey, recoveryCodes }: TwoFactorProps) {
    const toast = useToast();
    const confirm = useConfirm();
    const [isBusy, setIsBusy] = useState(false);
    const confirmForm = useForm({ code: '' });

    const visit = (method: 'post' | 'delete', url: string, successMessage: string) => {
        router.visit(url, {
            method,
            preserveScroll: true,
            onStart: () => setIsBusy(true),
            onFinish: () => setIsBusy(false),
            onSuccess: () => toast.success(__(successMessage)),
        });
    };

    const confirmSetup: FormEventHandler = (event) => {
        event.preventDefault();
        confirmForm.post(route('two-factor.confirm'), {
            preserveScroll: true,
            errorBag: 'confirmTwoFactorAuthentication',
            onSuccess: () => toast.success(__('Two-factor authentication is on.')),
            onFinish: () => confirmForm.reset(),
        });
    };

    const disable = async () => {
        const confirmed = await confirm({
            title: 'Turn off two-factor authentication?',
            description: __('Signing in will only need your password again.'),
            confirmLabel: 'Turn off',
            tone: 'danger',
        });

        if (confirmed) {
            visit('delete', route('two-factor.disable'), 'Two-factor authentication is off.');
        }
    };

    return (
        <>
            <Head title={__('Two-factor authentication')} />

            <FormSection
                icon={ShieldCheck}
                title="Two-factor authentication"
                description="Besides your password, signing in asks for a code from an authenticator app on your phone (Google Authenticator, Microsoft Authenticator, Authy…)."
                actions={
                    <Badge shape="pill" tone={state === 'enabled' ? 'success' : state === 'pending' ? 'warning' : 'neutral'}>
                        {state === 'enabled' ? __('On') : state === 'pending' ? __('Waiting for confirmation') : __('Off')}
                    </Badge>
                }
            >
                {state === 'disabled' && (
                    <Button onClick={() => visit('post', route('two-factor.enable'), 'Scan the QR code to finish.')} isLoading={isBusy}>
                        {!isBusy && <ShieldCheck />}
                        {__('Turn on two-factor authentication')}
                    </Button>
                )}

                {state === 'pending' && (
                    <div className="grid gap-6 lg:grid-cols-[auto_1fr]">
                        <div className="space-y-2">
                            <p className="text-ink-soft text-sm font-medium">{__('1. Scan this QR code with your authenticator app')}</p>
                            {qrCodeSvg && (
                                <div
                                    className="rounded-field border-line bg-surface inline-block border p-3 [&_svg]:size-44"
                                    // SVG generated by Fortify on the server.
                                    dangerouslySetInnerHTML={{ __html: qrCodeSvg }}
                                />
                            )}
                            {secretKey && (
                                <p className="text-ink-muted text-xs">
                                    {__('Or enter this key:')} <code className="text-ink font-mono">{secretKey}</code>
                                </p>
                            )}
                        </div>

                        <form onSubmit={confirmSetup} className="space-y-3 self-end">
                            <p className="text-ink-soft text-sm font-medium">{__('2. Enter the 6-digit code shown in the app')}</p>
                            <FormField
                                label="Authentication code"
                                htmlFor="code"
                                required
                                error={(confirmForm.errors as Record<string, string>).code}
                                className="max-w-56"
                            >
                                <Input
                                    id="code"
                                    value={confirmForm.data.code}
                                    onChange={(event) => confirmForm.setData('code', event.target.value.replace(/\D/g, '').slice(0, 6))}
                                    inputMode="numeric"
                                    autoComplete="one-time-code"
                                    placeholder="123456"
                                    className="font-mono tracking-[0.3em]"
                                    required
                                />
                            </FormField>
                            <div className="flex gap-2">
                                <Button type="submit" isLoading={confirmForm.processing}>
                                    {__('Confirm')}
                                </Button>
                                <Button variant="secondary" onClick={() => visit('delete', route('two-factor.disable'), 'Setup cancelled.')}>
                                    {__('Cancel')}
                                </Button>
                            </div>
                        </form>
                    </div>
                )}

                {state === 'enabled' && (
                    <Button variant="danger" onClick={disable} isLoading={isBusy}>
                        {!isBusy && <ShieldOff />}
                        {__('Turn off two-factor authentication')}
                    </Button>
                )}
            </FormSection>

            {state === 'enabled' && (
                <FormSection
                    icon={KeyRound}
                    title="Recovery codes"
                    description="Keep these codes somewhere safe. Each one can be used once to sign in if you lose your phone."
                    actions={
                        <>
                            <Button
                                variant="secondary"
                                size="sm"
                                onClick={() => {
                                    void navigator.clipboard?.writeText(recoveryCodes.join('\n'));
                                    toast.success(__('Recovery codes copied.'));
                                }}
                            >
                                <Copy /> {__('Copy')}
                            </Button>
                            <Button
                                variant="secondary"
                                size="sm"
                                onClick={() => visit('post', route('two-factor.regenerate-recovery-codes'), 'New recovery codes created.')}
                            >
                                <RefreshCw /> {__('Create new codes')}
                            </Button>
                        </>
                    }
                >
                    <ul className="rounded-field bg-surface-muted grid gap-1 p-3 font-mono text-sm sm:grid-cols-2">
                        {recoveryCodes.map((code) => (
                            <li key={code} className="text-ink">
                                {code}
                            </li>
                        ))}
                    </ul>
                </FormSection>
            )}
        </>
    );
}

/** Persistent layout: the shell stays mounted while navigating between pages. */
TwoFactor.layout = (page: ReactNode) => (
    <AdminLayout breadcrumbs={breadcrumbs} title="Two-factor authentication">
        <SettingsLayout>{page}</SettingsLayout>
    </AdminLayout>
);
